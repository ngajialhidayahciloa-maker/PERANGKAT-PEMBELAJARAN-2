// Helper to get questions preset by subject
export function getSubjectSampleQuestions(subjectName: string): QuestionItem[] | null {
  const norm = subjectName.toLowerCase();
  if (norm.includes('matematika') || norm.includes('mtk')) {
    return SAMPLE_QUESTIONS_MATEMATIKA;
  }
  if (norm.includes('fiqih') || norm.includes('fikih')) {
    return SAMPLE_QUESTIONS_FIQIH;
  }
  if (norm.includes('qur') || norm.includes('hadis') || norm.includes('hadits') || norm.includes('qurdis')) {
    return SAMPLE_QUESTIONS_QURDIS;
  }
  if (norm.includes('arab')) {
    return SAMPLE_QUESTIONS_BAHASA_ARAB;
  }
  return null;
}
